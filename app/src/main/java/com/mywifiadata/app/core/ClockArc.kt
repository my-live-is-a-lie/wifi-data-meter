package com.mywifiadata.app.core

/**
 * قوس استهلاك الباقة في «ساعة الاستهلاك» داخل التطبيق وفي أداة الشاشة الرئيسية.
 *
 * يبدأ القوس من منتصف أعلى الميناء (موضع الساعة 12) وينزل مع عقارب الساعة حتى
 * منتصف أسفله (موضع الساعة 6) عند استهلاك الباقة كاملة، فيقرأ المستخدم النسبة
 * كحركة نزول من الأعلى إلى الأسفل لا كحلقة تبدأ من الأسفل.
 */
object ClockArc {

    /** زاوية البداية بالدرجات: -90 هي منتصف أعلى الدائرة في Canvas. */
    const val START_ANGLE_DEG = -90f

    /** زاوية الامتلاء الكامل: نصف دورة من الأعلى إلى الأسفل. */
    const val FULL_SWEEP_DEG = 180f

    /**
     * زاوية القوس المعروضة لنسبة استهلاك [progress] بين صفر وواحد.
     * القيم خارج المجال تُقصّ فلا يتجاوز القوس منتصف الأسفل.
     */
    fun sweepAngleDeg(progress: Float): Float =
        FULL_SWEEP_DEG * progress.coerceIn(0f, 1f)
}
